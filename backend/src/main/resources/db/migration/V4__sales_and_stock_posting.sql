CREATE TABLE sales (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id bigint NOT NULL REFERENCES customers(id),warehouse_id bigint NOT NULL REFERENCES warehouses(id),
 date date NOT NULL,status integer NOT NULL CHECK(status BETWEEN 1 AND 4),version integer NOT NULL DEFAULT 0,
 tax_rate numeric(7,4) NOT NULL CHECK(tax_rate BETWEEN 0 AND 100),tax_amount numeric(19,4) NOT NULL,
 discount numeric(19,4) NOT NULL CHECK(discount>=0),shipping numeric(19,4) NOT NULL CHECK(shipping>=0),
 grand_total numeric(19,4) NOT NULL CHECK(grand_total>=0),notes varchar(2000) NOT NULL DEFAULT '',
 created_by bigint NOT NULL REFERENCES app_users(id),created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE sale_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,sale_id bigint NOT NULL REFERENCES sales(id),
 product_id bigint NOT NULL REFERENCES products(id),sale_unit bigint REFERENCES units(id),base_unit bigint NOT NULL REFERENCES base_units(id),
 quantity numeric(19,4) NOT NULL CHECK(quantity>0),product_price numeric(19,4) NOT NULL CHECK(product_price>=0),
 tax_type integer NOT NULL CHECK(tax_type IN (1,2)),tax_value numeric(7,4) NOT NULL CHECK(tax_value BETWEEN 0 AND 100),
 discount_type integer NOT NULL CHECK(discount_type IN (1,2)),discount_value numeric(19,4) NOT NULL CHECK(discount_value>=0),
 net_unit_price numeric(23,8) NOT NULL,discount_amount numeric(19,4) NOT NULL,tax_amount numeric(19,4) NOT NULL,sub_total numeric(19,4) NOT NULL,
 UNIQUE(sale_id,product_id),
 FOREIGN KEY(sale_unit,base_unit) REFERENCES units(id,base_unit)
);
CREATE INDEX sales_date_idx ON sales(date,id);
ALTER TABLE stock_operations ADD COLUMN sale_id bigint REFERENCES sales(id);
ALTER TABLE stock_operations DROP CONSTRAINT stock_operations_kind_check;
ALTER TABLE stock_operations ADD CONSTRAINT stock_operations_kind_check CHECK(kind IN ('OPENING','ADJUSTMENT','TRANSFER','PURCHASE','PURCHASE_CANCEL','SALE','SALE_CANCEL'));
ALTER TABLE stock_operations ADD CONSTRAINT one_stock_document CHECK(num_nonnulls(purchase_id,sale_id)<=1);
ALTER TABLE stock_operations ADD CONSTRAINT sale_operation_source CHECK((kind IN ('SALE','SALE_CANCEL'))=(sale_id IS NOT NULL));
CREATE UNIQUE INDEX sale_operation_once ON stock_operations(sale_id,kind) WHERE sale_id IS NOT NULL;
