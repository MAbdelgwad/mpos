CREATE TABLE document_payments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_id bigint REFERENCES sales(id), purchase_id bigint REFERENCES purchases(id),
 amount numeric(19,4) NOT NULL CHECK(amount>0), date date NOT NULL,
 method varchar(20) NOT NULL CHECK(method IN ('CASH','BANK','CARD')),
 reference varchar(120) NOT NULL DEFAULT '', notes varchar(1000) NOT NULL DEFAULT '',
 created_by bigint NOT NULL REFERENCES app_users(id), created_at timestamptz NOT NULL DEFAULT now(),
 voided_by bigint REFERENCES app_users(id), voided_at timestamptz, void_reason varchar(1000),
 CHECK(num_nonnulls(sale_id,purchase_id)=1),
 CHECK((voided_at IS NULL AND voided_by IS NULL AND void_reason IS NULL) OR
       (voided_at IS NOT NULL AND voided_by IS NOT NULL AND length(trim(void_reason))>0))
);
CREATE INDEX payment_sale_idx ON document_payments(sale_id,id) WHERE sale_id IS NOT NULL;
CREATE INDEX payment_purchase_idx ON document_payments(purchase_id,id) WHERE purchase_id IS NOT NULL;
INSERT INTO permissions(name,display_name) VALUES ('manage_payments','Payments');
