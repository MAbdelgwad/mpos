CREATE TABLE purchases (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 supplier_id bigint NOT NULL REFERENCES suppliers(id),warehouse_id bigint NOT NULL REFERENCES warehouses(id),
 date date NOT NULL,status integer NOT NULL CHECK(status BETWEEN 1 AND 4),version integer NOT NULL DEFAULT 0,
 tax_rate numeric(7,4) NOT NULL CHECK(tax_rate BETWEEN 0 AND 100),tax_amount numeric(19,4) NOT NULL,
 discount numeric(19,4) NOT NULL CHECK(discount>=0),shipping numeric(19,4) NOT NULL CHECK(shipping>=0),
 grand_total numeric(19,4) NOT NULL CHECK(grand_total>=0),notes varchar(2000) NOT NULL DEFAULT '',
 created_by bigint NOT NULL REFERENCES app_users(id),created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE purchase_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,purchase_id bigint NOT NULL REFERENCES purchases(id),
 product_id bigint NOT NULL REFERENCES products(id),purchase_unit bigint REFERENCES units(id),base_unit bigint NOT NULL REFERENCES base_units(id),
 quantity numeric(19,4) NOT NULL CHECK(quantity>0),product_cost numeric(19,4) NOT NULL CHECK(product_cost>=0),
 tax_type integer NOT NULL CHECK(tax_type IN (1,2)),tax_value numeric(7,4) NOT NULL CHECK(tax_value BETWEEN 0 AND 100),
 discount_type integer NOT NULL CHECK(discount_type IN (1,2)),discount_value numeric(19,4) NOT NULL CHECK(discount_value>=0),
 net_unit_cost numeric(23,8) NOT NULL,discount_amount numeric(19,4) NOT NULL,tax_amount numeric(19,4) NOT NULL,sub_total numeric(19,4) NOT NULL,
 UNIQUE(purchase_id,product_id),
 FOREIGN KEY(purchase_unit,base_unit) REFERENCES units(id,base_unit)
);
CREATE INDEX purchases_date_idx ON purchases(date,id);
CREATE TABLE stock_operations (
 id uuid PRIMARY KEY,kind varchar(30) NOT NULL CHECK(kind IN ('OPENING','ADJUSTMENT','TRANSFER','PURCHASE','PURCHASE_CANCEL')),
 purchase_id bigint REFERENCES purchases(id),reason varchar(1000) NOT NULL,created_by bigint NOT NULL REFERENCES app_users(id),created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX purchase_operation_once ON stock_operations(purchase_id,kind) WHERE purchase_id IS NOT NULL;
CREATE TABLE stock_balances (
 warehouse_id bigint REFERENCES warehouses(id),product_id bigint REFERENCES products(id),quantity numeric(19,4) NOT NULL DEFAULT 0 CHECK(quantity>=0),
 PRIMARY KEY(warehouse_id,product_id)
);
CREATE TABLE stock_movements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,operation_id uuid NOT NULL REFERENCES stock_operations(id),
 warehouse_id bigint NOT NULL REFERENCES warehouses(id),product_id bigint NOT NULL REFERENCES products(id),
 quantity_delta numeric(19,4) NOT NULL CHECK(quantity_delta<>0),quantity_after numeric(19,4) NOT NULL CHECK(quantity_after>=0),created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX stock_movements_product_idx ON stock_movements(warehouse_id,product_id,id);
CREATE TABLE request_keys (
 scope varchar(80) NOT NULL,key varchar(128) NOT NULL,fingerprint char(64) NOT NULL,response jsonb,
 PRIMARY KEY(scope,key)
);
